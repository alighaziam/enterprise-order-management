function t(key, vars) {
  const lang = (typeof state !== "undefined" && state.lang) || (document.documentElement.lang === "fa" ? "fa" : "en");
  const pack = TEXT[lang] || TEXT.en;
  let value = pack[key] ?? TEXT.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, replacement]) => {
      value = value.replaceAll("{" + name + "}", replacement);
    });
  }
  return value;
}

function applyLocale() {
  const fa = state.lang === "fa";
  document.documentElement.lang = fa ? "fa" : "en";
  document.documentElement.dir = fa ? "rtl" : "ltr";
  document.title = t("appTitle");
  document.querySelector("#brand-name").textContent = t("brand.name");
  document.querySelector("#brand-note").textContent = t("brand.note");
  document.querySelector("#legal").textContent = t("legal");
  document.querySelector("#refresh").textContent = t("refresh");
  document.querySelector("#new-checkout").textContent = t("newCheckout");
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const on = button.dataset.lang === state.lang;
    button.classList.toggle("active", on);
    button.setAttribute("aria-pressed", on ? "true" : "false");
  });
}
